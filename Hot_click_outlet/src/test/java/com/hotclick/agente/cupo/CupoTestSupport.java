package com.hotclick.agente.cupo;

import com.hotclick.agente.canal.CanalCuenta;
import com.hotclick.agente.conversacion.ConversacionActiva;
import com.hotclick.agente.conversacion.ModoConversacion;
import com.hotclick.agente.conversacion.PerfilConversacion;
import com.hotclick.agente.webhook.MensajeEntrante.Canal;
import com.hotclick.model.Empresa;
import com.hotclick.model.Plan;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.List;
import java.util.UUID;

/** Esquema H2 y fábricas comunes de las pruebas de AG-29. */
final class CupoTestSupport {

    static final Instant AHORA = Instant.parse("2026-12-10T15:00:00Z");
    static final Clock RELOJ = Clock.fixed(AHORA, ZoneOffset.UTC);

    private CupoTestSupport() { }

    static JdbcTemplate baseH2() {
        JdbcTemplate jdbc = new JdbcTemplate(new DriverManagerDataSource(
            "jdbc:h2:mem:cupo" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("CREATE TABLE hot_click_agente_uso_mes_tb (id_uso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_empresa BIGINT, empresa_clave BIGINT NOT NULL DEFAULT 0, mes DATE NOT NULL, "
            + "conversaciones INTEGER NOT NULL DEFAULT 0, costo_usd NUMERIC(12,6) NOT NULL DEFAULT 0, "
            + "aviso_80_en TIMESTAMP WITH TIME ZONE, aviso_100_en TIMESTAMP WITH TIME ZONE, "
            + "CONSTRAINT uq_agente_uso_mes UNIQUE (empresa_clave, mes))");
        jdbc.execute("CREATE TABLE hot_click_agente_conv_mes_tb (empresa_clave BIGINT NOT NULL DEFAULT 0, "
            + "mes DATE NOT NULL, contacto_hash VARCHAR(64) NOT NULL, fk_id_empresa BIGINT, "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, "
            + "PRIMARY KEY (empresa_clave, mes, contacto_hash))");
        jdbc.execute("CREATE TABLE hot_click_agente_baja_tb (id_baja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_empresa BIGINT, canal VARCHAR(20) NOT NULL, contacto_hash VARCHAR(64) NOT NULL, "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, CONSTRAINT uq_agente_baja_hash UNIQUE (contacto_hash))");
        return jdbc;
    }

    static Plan plan(String nombre, boolean agente, int cupo) {
        Plan p = new Plan();
        p.setNombre(nombre);
        p.setTieneAgente(agente);
        p.setMaxConversacionesAgente(cupo);
        return p;
    }

    static Empresa empresa(Plan plan, String correo) {
        Empresa e = new Empresa();
        e.setCorreoEmpresa(correo);
        e.setPlan(plan);
        return e;
    }

    static CanalCuenta cuenta(Long empresaId) {
        CanalCuenta c = new CanalCuenta();
        c.setId(10L);
        c.setTipo(Canal.WHATSAPP);
        c.setIdExterno("PNID-1");
        c.setEmpresaId(empresaId);
        return c;
    }

    static ConversacionActiva conversacion(Long empresaId, PerfilConversacion perfil, String contacto) {
        return new ConversacionActiva(UUID.randomUUID(), perfil, empresaId, cuenta(empresaId), contacto, null,
            ModoConversacion.BOT, AHORA, List.of());
    }
}
