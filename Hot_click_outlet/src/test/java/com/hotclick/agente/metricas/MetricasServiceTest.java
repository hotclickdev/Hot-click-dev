package com.hotclick.agente.metricas;

import com.hotclick.agente.metricas.MetricasDtos.Metricas;
import com.hotclick.agente.metricas.MetricasDtos.Respuesta;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * AG-32: las consultas agregadas con varias empresas. Base H2 propia (modo PostgreSQL) con solo las columnas que
 * usan las consultas: verifica sumas, conversión por bot y canal, aislamiento entre negocios y rango de fechas.
 */
class MetricasServiceTest {

    private static final ZoneId CR = ZoneId.of("America/Costa_Rica");
    private static final Clock RELOJ = Clock.fixed(Instant.parse("2026-12-10T18:00:00Z"), CR);
    private static final LocalDate DESDE = LocalDate.of(2026, 12, 1);
    private static final LocalDate HASTA = LocalDate.of(2026, 12, 10);

    private JdbcTemplate jdbc;
    private MetricasService service;

    @BeforeEach
    void init() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
            "jdbc:h2:mem:metricas" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("CREATE TABLE hot_click_chat_sesion_tb (id_sesion UUID PRIMARY KEY, fk_id_empresa BIGINT, "
            + "canal VARCHAR(20) NOT NULL, fk_id_canal_cuenta BIGINT, perfil VARCHAR(20), modo VARCHAR(10) NOT NULL, "
            + "iniciada_en TIMESTAMP WITH TIME ZONE NOT NULL)");
        jdbc.execute("CREATE TABLE hot_click_enlace_compra_tb (id_enlace_compra BIGINT GENERATED BY DEFAULT AS IDENTITY "
            + "PRIMARY KEY, fk_id_empresa BIGINT, fk_id_chat_sesion UUID, canal VARCHAR(20) NOT NULL, "
            + "estado VARCHAR(15) NOT NULL, precio_total_creado INTEGER NOT NULL, creado TIMESTAMP NOT NULL, "
            + "abierto TIMESTAMP)");
        jdbc.execute("CREATE TABLE hot_click_pedido_tb (id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_empresa BIGINT, origen_canal VARCHAR(20), estado_pedido VARCHAR(30), total_pedido INTEGER NOT NULL, "
            + "fecha_pedido TIMESTAMP)");
        jdbc.execute("CREATE TABLE hot_click_agente_uso_mes_tb (id_uso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_empresa BIGINT, mes DATE NOT NULL, conversaciones INTEGER NOT NULL DEFAULT 0, "
            + "costo_usd NUMERIC(12,6) NOT NULL DEFAULT 0)");
        jdbc.execute("CREATE TABLE hot_click_agente_alerta_meta_tb (id_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY "
            + "PRIMARY KEY, campo VARCHAR(40) NOT NULL, evento VARCHAR(40), limite VARCHAR(40), "
            + "cuenta_externa VARCHAR(40), creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP)");
        service = new MetricasService(new MetricasRepositorio(jdbc), new AlertaMetaRepositorio(jdbc), RELOJ);
    }

    private UUID sesion(Long empresa, String canal, String perfil, String modo, String cuando) {
        UUID id = UUID.randomUUID();
        jdbc.update("INSERT INTO hot_click_chat_sesion_tb VALUES (?, ?, ?, 1, ?, ?, ?)", id, empresa, canal, perfil, modo,
            java.sql.Timestamp.from(Instant.parse(cuando)));
        return id;
    }

    private void enlace(Long empresa, UUID sesion, String canal, String estado, int precio, String creado, boolean abierto) {
        jdbc.update("INSERT INTO hot_click_enlace_compra_tb (fk_id_empresa, fk_id_chat_sesion, canal, estado, "
                + "precio_total_creado, creado, abierto) VALUES (?, ?, ?, ?, ?, ?, ?)",
            empresa, sesion, canal, estado, precio, java.sql.Timestamp.valueOf(creado),
            abierto ? java.sql.Timestamp.valueOf(creado) : null);
    }

    private void pedido(Long empresa, String origen, String estado, int total, String fecha) {
        jdbc.update("INSERT INTO hot_click_pedido_tb (fk_id_empresa, origen_canal, estado_pedido, total_pedido, "
            + "fecha_pedido) VALUES (?, ?, ?, ?, ?)", empresa, origen, estado, total, java.sql.Timestamp.valueOf(fecha));
    }

    private void uso(Long empresa, String mes, int convs, String costo) {
        jdbc.update("INSERT INTO hot_click_agente_uso_mes_tb (fk_id_empresa, mes, conversaciones, costo_usd) "
            + "VALUES (?, ?, ?, ?)", empresa, java.sql.Date.valueOf(mes), convs, new BigDecimal(costo));
    }

    /** Negocio 7: 3 conversaciones de ventas (2 WhatsApp, 1 Instagram), una pasó a persona. Negocio 8: ruido. */
    private void datos() {
        UUID a = sesion(7L, "WHATSAPP", "NEGOCIO_VENTAS", "BOT", "2026-12-02T15:00:00Z");
        UUID b = sesion(7L, "WHATSAPP", "NEGOCIO_VENTAS", "PERSONA", "2026-12-03T15:00:00Z");
        UUID c = sesion(7L, "INSTAGRAM", "NEGOCIO_VENTAS", "BOT", "2026-12-04T15:00:00Z");
        sesion(7L, "WHATSAPP", "NEGOCIO_INTERNO", "BOT", "2026-12-04T15:00:00Z"); // modo interno: no cuenta
        sesion(7L, "WHATSAPP", "NEGOCIO_VENTAS", "BOT", "2026-11-20T15:00:00Z");  // fuera del rango
        enlace(7L, a, "WHATSAPP", "PAGADO", 10000, "2026-12-02 10:00:00", true);
        enlace(7L, b, "WHATSAPP", "VENCIDO", 7000, "2026-12-03 10:00:00", false);
        enlace(7L, c, "INSTAGRAM", "ABIERTO", 5000, "2026-12-04 10:00:00", true);
        enlace(7L, null, "WHATSAPP", "CREADO", 3000, "2026-12-05 10:00:00", false);
        enlace(7L, a, "WHATSAPP", "PAGADO", 1, "2026-11-01 10:00:00", true);      // fuera del rango
        pedido(7L, "WHATSAPP", "PAGADO", 10000, "2026-12-02 10:30:00");
        pedido(7L, "WHATSAPP", "ENTREGADO", 4000, "2026-12-06 10:30:00");
        pedido(7L, "INSTAGRAM", "PENDIENTE", 9999, "2026-12-04 10:30:00");        // sin cobrar: no cuenta
        pedido(7L, null, "PAGADO", 8888, "2026-12-04 10:30:00");                  // no vino del bot
        uso(7L, "2026-12-01", 3, "0.500000");
        uso(7L, "2026-11-01", 90, "9.000000");                                      // mes fuera del rango

        // Otro negocio: nada de esto puede aparecer en las cifras del 7.
        UUID x = sesion(8L, "WHATSAPP", "NEGOCIO_VENTAS", "BOT", "2026-12-02T15:00:00Z");
        enlace(8L, x, "WHATSAPP", "PAGADO", 50000, "2026-12-02 10:00:00", true);
        pedido(8L, "WHATSAPP", "PAGADO", 50000, "2026-12-02 10:30:00");
        uso(8L, "2026-12-01", 1, "2.000000");

        // Bot de HotClick (sin empresa).
        UUID h = sesion(null, "WHATSAPP", "HOTCLICK", "BOT", "2026-12-05T15:00:00Z");
        enlace(null, h, "WHATSAPP", "PAGADO", 20000, "2026-12-05 10:00:00", true);
        pedido(null, "WHATSAPP", "PAGADO", 20000, "2026-12-05 10:30:00");
        uso(null, "2026-12-01", 1, "0.250000");
    }

    @Test
    void negocioVeSoloLoSuyoConEmbudoVentasYCostos() {
        datos();

        Respuesta r = service.consultar(7L, DESDE, HASTA);

        assertThat(r.alcance()).isEqualTo("NEGOCIO");
        assertThat(r.plataforma()).isNull();
        assertThat(r.alertasMeta()).isNull();
        Metricas m = r.propias();
        assertThat(m.embudo().conversaciones()).isEqualTo(3);
        assertThat(m.embudo().enlacesCreados()).isEqualTo(4);
        assertThat(m.embudo().enlacesAbiertos()).isEqualTo(2);          // pagado + abierto
        assertThat(m.embudo().enlacesPagados()).isEqualTo(1);
        assertThat(m.traspasosAPersona()).isEqualTo(1);
        assertThat(m.perdidas().cantidad()).isEqualTo(1);
        assertThat(m.perdidas().totalColones()).isEqualTo(7000);
        assertThat(m.ventas().cantidad()).isEqualTo(2);
        assertThat(m.ventas().totalColones()).isEqualTo(14000);
        assertThat(m.ventas().porCanal()).extracting(MetricasDtos.VentaCanal::canal).containsExactly("WHATSAPP");
        assertThat(m.costos().costoUsd()).isEqualByComparingTo("0.5");
        assertThat(m.costos().costoPorVentaUsd()).isEqualByComparingTo("0.25");
        assertThat(m.costos().conversacionesCobradas()).isEqualTo(3);
    }

    @Test
    void conversionPorBotYPorCanal() {
        datos();

        Metricas m = service.consultar(7L, DESDE, HASTA).propias();

        assertThat(m.porBot()).extracting(MetricasDtos.Segmento::clave).containsExactly("NEGOCIO_VENTAS", "SIN_PERFIL");
        MetricasDtos.Segmento ventas = m.porBot().get(0);
        assertThat(ventas.conversaciones()).isEqualTo(3);
        assertThat(ventas.enlacesCreados()).isEqualTo(3);              // el enlace sin conversación cae en SIN_PERFIL
        assertThat(ventas.enlacesPagados()).isEqualTo(1);
        assertThat(ventas.conversionPct()).isEqualTo(33.3);
        MetricasDtos.Segmento wa = m.porCanal().stream().filter(s -> s.clave().equals("WHATSAPP")).findFirst().orElseThrow();
        assertThat(wa.conversaciones()).isEqualTo(2);
        assertThat(wa.enlacesCreados()).isEqualTo(3);
        assertThat(wa.enlacesPagados()).isEqualTo(1);
        assertThat(wa.conversionPct()).isEqualTo(50.0);
    }

    @Test
    void otroNegocioNoVeLasCifrasDelPrimero() {
        datos();

        Metricas m = service.consultar(8L, DESDE, HASTA).propias();

        assertThat(m.embudo().conversaciones()).isEqualTo(1);
        assertThat(m.embudo().enlacesPagados()).isEqualTo(1);
        assertThat(m.ventas().totalColones()).isEqualTo(50000);
        assertThat(m.costos().costoUsd()).isEqualByComparingTo("2");
    }

    @Test
    void negocioSinDatosDevuelveCerosYCostoPorVentaNulo() {
        datos();

        Metricas m = service.consultar(99L, DESDE, HASTA).propias();

        assertThat(m.embudo().conversaciones()).isZero();
        assertThat(m.ventas().cantidad()).isZero();
        assertThat(m.costos().costoPorVentaUsd()).isNull();
        assertThat(m.porBot()).isEmpty();
    }

    @Test
    void adminVeHotClickPorSeparadoYElTotalDeLaPlataforma() {
        datos();
        jdbc.update("INSERT INTO hot_click_agente_alerta_meta_tb (campo, evento) VALUES ('account_update', 'DOWNGRADE')");

        Respuesta r = service.consultar(null, DESDE, HASTA);

        assertThat(r.alcance()).isEqualTo("HOTCLICK");
        assertThat(r.propias().embudo().conversaciones()).isEqualTo(1);          // solo el bot de HotClick
        assertThat(r.propias().ventas().totalColones()).isEqualTo(20000);
        assertThat(r.plataforma().embudo().conversaciones()).isEqualTo(5);       // 3 + 1 + 1
        assertThat(r.plataforma().ventas().cantidad()).isEqualTo(4);             // 2 + 1 + 1
        assertThat(r.plataforma().ventas().totalColones()).isEqualTo(84000);     // 14000 + 50000 + 20000
        assertThat(r.plataforma().costos().costoUsd()).isEqualByComparingTo("2.75");
        assertThat(r.alertasMeta()).hasSize(1);
        assertThat(r.alertasMeta().get(0).evento()).isEqualTo("DOWNGRADE");
    }

    @Test
    void sinFechasUsaLosUltimos30Dias() {
        Respuesta r = service.consultar(7L, null, null);

        assertThat(r.hasta()).isEqualTo(LocalDate.of(2026, 12, 10));
        assertThat(r.desde()).isEqualTo(LocalDate.of(2026, 11, 11));
    }

    @Test
    void rangoInvalidoSeRechaza() {
        assertThatThrownBy(() -> service.consultar(7L, HASTA, DESDE)).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> service.consultar(7L, LocalDate.of(2025, 1, 1), HASTA))
            .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("366");
    }

    @Test
    void porcentajeRedondeaAUnDecimal() {
        assertThat(MetricasService.porcentaje(1, 3)).isEqualTo(33.3);
        assertThat(MetricasService.porcentaje(2, 3)).isEqualTo(66.7);
        assertThat(MetricasService.porcentaje(5, 0)).isZero();
    }
}
