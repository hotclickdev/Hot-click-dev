/** Esquema H2 y fábricas comunes de las pruebas de campañas (AG-36). Sin Meta real ni datos reales. */
final class CampanaTestSupport {

    static final Instant AHORA = Instant.parse("2026-12-10T15:00:00Z");
    static final Clock RELOJ = Clock.fixed(AHORA, ZoneOffset.UTC);
    static final HasherInterno HASHER = new HasherInterno("");

    private CampanaTestSupport() { }

    static JdbcTemplate baseH2() {
        JdbcTemplate jdbc = new JdbcTemplate(new DriverManagerDataSource(
            "jdbc:h2:mem:camp" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("CREATE TABLE hot_click_agente_consentimiento_tb (id_consentimiento BIGINT GENERATED BY DEFAULT AS "
            + "IDENTITY PRIMARY KEY, fk_id_empresa BIGINT NOT NULL, canal VARCHAR(20) NOT NULL, contacto_hash VARCHAR(64) "
            + "NOT NULL, contacto_ultimos4 VARCHAR(4), contacto_cifrado VARCHAR(2000), nombre VARCHAR(120), "
            + "estado VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL, origen VARCHAR(20) NOT NULL, evidencia VARCHAR(300) NOT NULL, "
            + "version_texto VARCHAR(20) NOT NULL, consentido_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, "
            + "revocado_en TIMESTAMP WITH TIME ZONE, CONSTRAINT uq_consent_hash UNIQUE (contacto_hash))");
        jdbc.execute("CREATE TABLE hot_click_agente_baja_tb (id_baja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_empresa BIGINT, canal VARCHAR(20) NOT NULL, contacto_hash VARCHAR(64) NOT NULL, "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, CONSTRAINT uq_agente_baja_hash UNIQUE (contacto_hash))");
        jdbc.execute("CREATE TABLE hot_click_agente_plantilla_mkt_tb (id_plantilla BIGINT GENERATED BY DEFAULT AS IDENTITY "
            + "PRIMARY KEY, fk_id_empresa BIGINT NOT NULL, nombre VARCHAR(100) NOT NULL, idioma VARCHAR(10) DEFAULT 'es' NOT NULL, "
            + "cuerpo VARCHAR(1024) NOT NULL, ejemplos VARCHAR(2000), estado VARCHAR(12) DEFAULT 'PENDIENTE' NOT NULL, "
            + "meta_plantilla_id VARCHAR(64), motivo_rechazo VARCHAR(200), "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, "
            + "actualizado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, "
            + "CONSTRAINT uq_plantilla UNIQUE (fk_id_empresa, nombre, idioma))");
        jdbc.execute("CREATE TABLE hot_click_agente_campana_tb (id_campana BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_empresa BIGINT NOT NULL, fk_id_plantilla BIGINT NOT NULL, nombre VARCHAR(120) NOT NULL, "
            + "segmento VARCHAR(30) NOT NULL, segmento_dias INTEGER, segmento_categoria_id BIGINT, parametros VARCHAR(2000), "
            + "estado VARCHAR(12) DEFAULT 'BORRADOR' NOT NULL, programada_para TIMESTAMP WITH TIME ZONE, "
            + "destinatarios INTEGER DEFAULT 0 NOT NULL, costo_estimado_usd NUMERIC(12,4) DEFAULT 0 NOT NULL, "
            + "lanzada_en TIMESTAMP WITH TIME ZONE, finalizada_en TIMESTAMP WITH TIME ZONE, fk_id_usuario BIGINT, "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL)");
        jdbc.execute("CREATE TABLE hot_click_agente_campana_envio_tb (id_envio BIGINT GENERATED BY DEFAULT AS IDENTITY "
            + "PRIMARY KEY, fk_id_campana BIGINT NOT NULL, fk_id_empresa BIGINT NOT NULL, contacto_hash VARCHAR(64) NOT NULL, "
            + "estado VARCHAR(12) DEFAULT 'PENDIENTE' NOT NULL, motivo VARCHAR(40), intentos INTEGER DEFAULT 0 NOT NULL, "
            + "meta_mensaje_id VARCHAR(120), enviado_en TIMESTAMP WITH TIME ZONE, entregado_en TIMESTAMP WITH TIME ZONE, "
            + "leido_en TIMESTAMP WITH TIME ZONE, respondido_en TIMESTAMP WITH TIME ZONE, "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, "
            + "CONSTRAINT uq_envio UNIQUE (fk_id_campana, contacto_hash))");
        jdbc.execute("CREATE TABLE hot_click_enlace_compra_tb (id_enlace_compra BIGINT GENERATED BY DEFAULT AS IDENTITY "
            + "PRIMARY KEY, fk_id_empresa BIGINT, contacto_externo VARCHAR(100), canal VARCHAR(20) NOT NULL, "
            + "estado VARCHAR(15) NOT NULL, creado TIMESTAMP NOT NULL)");
        jdbc.execute("CREATE TABLE hot_click_enlace_compra_item_tb (id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fk_id_enlace_compra BIGINT NOT NULL, fk_id_producto BIGINT NOT NULL)");
        jdbc.execute("CREATE TABLE hot_click_producto_tb (id_producto BIGINT PRIMARY KEY, fk_id_empresa BIGINT, "
            + "fk_id_categoria BIGINT)");
        jdbc.execute("CREATE TABLE hot_click_lead_tb (id_lead BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "tipo VARCHAR(12) NOT NULL, fk_id_empresa BIGINT, canal VARCHAR(20), contacto_cifrado VARCHAR(2000), "
            + "creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP)");
        return jdbc;
    }

    /** Cifrado de mentira reversible: no usa llaves reales. */
    static TotpSecretEncryptionService cifrado() {
        TotpSecretEncryptionService c = mock(TotpSecretEncryptionService.class);
        when(c.encryptContactoCampana(anyString())).thenAnswer(i -> "c:" + i.getArgument(0));
        when(c.decryptContactoCampana(anyString())).thenAnswer(i -> ((String) i.getArgument(0)).substring(2));
        when(c.encryptContactoLead(anyString())).thenAnswer(i -> "l:" + i.getArgument(0));
        when(c.decryptContactoLead(anyString())).thenAnswer(i -> ((String) i.getArgument(0)).substring(2));
        return c;
    }

    static CampanaConfig config(int topeContacto, int topeMensual) {
        return new CampanaConfig(topeContacto, topeMensual, topeMensual, topeMensual, new BigDecimal("0.074"), 50, 3, RELOJ);
    }

    static CanalCuenta cuenta(Long empresaId) {
        CanalCuenta c = new CanalCuenta();
        c.setId(5L);
        c.setTipo(Canal.WHATSAPP);
        c.setEmpresaId(empresaId);
        c.setIdExterno("PNID");
        c.setWabaId("WABA1");
        c.setEstado(EstadoCanal.ACTIVA);
        return c;
    }

    static String hash(Long empresaId, String contacto) {
        return HASHER.contacto(empresaId, "WHATSAPP", contacto);
    }
}
