    id_pago BIGINT,
    merchant_token VARCHAR(500),
    monto INTEGER,
    moneda VARCHAR(3),
    redirect_url VARCHAR(1000)
) AS $$
DECLARE
    v_merchant_token VARCHAR(500);
    v_id_pago BIGINT;
BEGIN
    v_merchant_token := 'PAYXPERT-' || UPPER(SUBSTRING(MD5(RANDOM()::TEXT || EXTRACT(EPOCH FROM NOW())::TEXT), 1, 32));
    
    INSERT INTO hot_click_pago_tb (
        merchant_token, redirect_url, monto, moneda, estado_pago, metodo_pago_tipo,
        fecha_expiracion, fk_id_pedido, fk_id_usuario, fk_id_estado
    ) VALUES (
        v_merchant_token, p_redirect_url, p_monto, p_moneda, 'PENDIENTE', p_metodo_pago_tipo,
        CURRENT_TIMESTAMP + INTERVAL '2 hours', p_id_pedido, p_id_usuario, 1
    ) RETURNING id_pago INTO v_id_pago;
    
    RETURN QUERY SELECT p.id_pago, p.merchant_token, p.monto, p.moneda, p.redirect_url
    FROM hot_click_pago_tb p WHERE p.id_pago = v_id_pago;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION fn_obtener_pago_por_token(
    p_merchant_token VARCHAR(500)
) RETURNS TABLE(
    id_pago BIGINT, merchant_token VARCHAR(500), monto INTEGER, moneda VARCHAR(3),
    estado_pago VARCHAR(30), metodo_pago_tipo VARCHAR(30), fecha_creacion TIMESTAMP,
    fecha_expiracion TIMESTAMP, id_pedido BIGINT, numero_pedido VARCHAR(20),
    total_pedido INTEGER, nombre_usuario VARCHAR(100), correo_usuario VARCHAR(100)
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        p.id_pago, p.merchant_token, p.monto, p.moneda, p.estado_pago, p.metodo_pago_tipo,
        p.fecha_creacion, p.fecha_expiracion, ped.id_pedido, ped.numero_pedido,
        ped.total_pedido, u.nombre || ' ' || u.apellido_paterno, u.correo
    FROM hot_click_pago_tb p
    JOIN HOT_CLICK_PEDIDO_TB ped ON p.fk_id_pedido = ped.id_pedido
    JOIN HOT_CLICK_USUARIO_TB u ON p.fk_id_usuario = u.id_usuario
    WHERE p.merchant_token = p_merchant_token AND p.fk_id_estado = 1;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

