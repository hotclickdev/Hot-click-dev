-- ============================================================================
-- ESQUEMA BASE PARA UNA BASE VACÍA (equivalente a V1 tal como quedó en prod)
--
-- NO es una migración de db/migration: Flyway principal nunca lo ve y prod nunca
-- lo ejecuta (FlywayRepairConfig solo lo corre si el esquema public está VACÍO y
-- hotclick.flyway.base-vacia.enabled=true). No cambia el checksum de ninguna
-- migración aplicada.
--
-- Por qué existe: V1__initial_schema.sql es un dump legacy. En prod se adoptó con
-- baseline V1 (nunca se ejecutó), sobre una base que ya tenía las tablas legacy
-- "HOT_CLICK_*_TB" (comillas, mayúsculas) y las tablas en minúsculas que creó
-- Hibernate (ddl-auto=update). V2..VN usan ambas formas, así que V1 no se puede
-- rejugar en cadena (42P01 relation hot_click_producto_tb does not exist, línea 1372).
--
-- Composición (en orden):
--   1. V1 líneas 1-1368 sin cambios (tablas legacy entre comillas), sin BEGIN/COMMIT.
--   2. Tablas en minúsculas que en prod creó Hibernate antes del baseline y que
--      V1 (sección incremental) o V2+ asumen. Definición tomada del mapeo JPA
--      (pg_dump de Hibernate); NOT NULL relajado salvo PK (Hibernate no pone defaults).
--   3. V1 líneas 1369-fin (sección incremental 2026-05-13+), sin cambios salvo un
--      ADD COLUMN IF NOT EXISTS previo marcado [bootstrap].
--   4. Ajustes [bootstrap] documentados al final.
--   Incluye las 6 tablas JPA en minúsculas (carrito_item, estado, giro_ruleta, premio,
--   referido, resultado_ruleta) que prod recibió de Hibernate; una base ya construida
--   con la versión anterior (staging) necesita reconstruirse.
-- Prerrequisito: CREATE EXTENSION vector por un superusuario (V62).
-- Después: baseline V1 en flyway_schema_history y migrate() normal V2..VN
-- (con db/base-vacia/hooks/V2__antes_de_V71.sql entre V70 y V71).
-- ============================================================================

