CREATE OR REPLACE FUNCTION fn_crear_pago(
    p_id_pedido BIGINT,
    p_id_usuario INTEGER,
    p_monto INTEGER,
    p_moneda VARCHAR(3) DEFAULT 'CRC',
    p_metodo_pago_tipo VARCHAR(30) DEFAULT 'PAYXPERT_TARJETA',
    p_redirect_url VARCHAR(1000) DEFAULT NULL
) RETURNS TABLE(
    id_pago BIGINT,
    merchant_token VARCHAR(500),
    monto INTEGER,
    moneda VARCHAR(3),
    redirect_url VARCHAR(1000)
) AS $$
DECLARE
    v_merchant_token VARCHAR(500);
    v_id_pago BIGINT;
BEGIN
    v_merchant_token := 'PAYXPERT-' || UPPER(SUBSTRING(MD5(RANDOM()::TEXT || EXTRACT(EPOCH FROM NOW())::TEXT), 1, 32));
    
    INSERT INTO hot_click_pago_tb (
        merchant_token, redirect_url, monto, moneda, estado_pago, metodo_pago_tipo,
        fecha_expiracion, fk_id_pedido, fk_id_usuario, fk_id_estado
    ) VALUES (
        v_merchant_token, p_redirect_url, p_monto, p_moneda, 'PENDIENTE', p_metodo_pago_tipo,
        CURRENT_TIMESTAMP + INTERVAL '2 hours', p_id_pedido, p_id_usuario, 1
    ) RETURNING id_pago INTO v_id_pago;
    
    RETURN QUERY SELECT p.id_pago, p.merchant_token, p.monto, p.moneda, p.redirect_url
    FROM hot_click_pago_tb p WHERE p.id_pago = v_id_pago;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

