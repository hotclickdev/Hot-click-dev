        ped.total_pedido, u.nombre || ' ' || u.apellido_paterno, u.correo
    FROM hot_click_pago_tb p
    JOIN HOT_CLICK_PEDIDO_TB ped ON p.fk_id_pedido = ped.id_pedido
    JOIN HOT_CLICK_USUARIO_TB u ON p.fk_id_usuario = u.id_usuario
    WHERE p.merchant_token = p_merchant_token AND p.fk_id_estado = 1;
END;
